import { mkdir, readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import { render } from "@react-email/render"
import { JinjaTokens } from "../components/jinja"
import { TransactionalEmail } from "../components/transactional"
import DailyDigestEmail from "../emails/daily-digest"
import FoundationEmail from "../emails/foundation"
import WeeklyOverviewEmail from "../emails/weekly-overview"
import type { TransactionalKind } from "../fixtures/transactional-types"

const destination = new URL(
  "../../backend/app/email-templates/build/",
  import.meta.url,
)
const check = process.argv.includes("--check")
const tokens = new JinjaTokens()
const html = tokens.restore(await render(<FoundationEmail tokens={tokens} />))
// Text is deliberately authored separately: HTML-to-text conversion at build time
// cannot preserve runtime Jinja loops and branches reliably.
const text = await readFile(
  new URL("../emails/foundation.txt.jinja", import.meta.url),
  "utf8",
)
const dailyTokens = new JinjaTokens()
const dailyHtml = dailyTokens.restore(
  await render(<DailyDigestEmail tokens={dailyTokens} />),
)
const dailyText = await readFile(
  new URL("../emails/daily-digest.txt.jinja", import.meta.url),
  "utf8",
)
const weeklyTokens = new JinjaTokens()
const weeklyHtml = weeklyTokens.restore(
  await render(<WeeklyOverviewEmail tokens={weeklyTokens} />),
)
const weeklyText = await readFile(
  new URL("../emails/weekly-overview.txt.jinja", import.meta.url),
  "utf8",
)
const generated: Record<string, string> = {
  "weekly_monthly_overview_report.html": `<!-- Generated by emails/scripts/export.tsx. Do not edit. -->\n${weeklyHtml}\n`,
  "weekly_monthly_overview_report.txt": weeklyText,
  "daily_obligation_report.html": `<!-- Generated by emails/scripts/export.tsx. Do not edit. -->\n${dailyHtml}\n`,
  "daily_obligation_report.txt": dailyText,
  "foundation.html": `<!-- Generated by emails/scripts/export.tsx. Do not edit. -->\n${html}\n`,
  "foundation.txt": text,
}
const transactionalKinds: TransactionalKind[] = [
  "reset_password",
  "user_invitation",
  "new_account",
  "test_email",
]
for (const kind of transactionalKinds) {
  const transactionalTokens = new JinjaTokens()
  const transactionalHtml = transactionalTokens.restore(
    await render(
      <TransactionalEmail kind={kind} tokens={transactionalTokens} />,
    ),
  )
  generated[`${kind}.html`] =
    `<!-- Generated by emails/scripts/export.tsx. Do not edit. -->\n${transactionalHtml}\n`
  generated[`${kind}.txt`] = await readFile(
    new URL(`../emails/${kind}.txt.jinja`, import.meta.url),
    "utf8",
  )
}
await mkdir(destination, { recursive: true })
for (const [name, content] of Object.entries(generated)) {
  const path = new URL(name, destination)
  if (check) {
    let current: string | undefined
    try {
      current = await readFile(path, "utf8")
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error
    }
    if (current !== content)
      throw new Error(
        `${fileURLToPath(path)} is stale. Run bun run email:export and commit the result.`,
      )
  } else {
    await writeFile(path, content)
  }
}
console.log(
  check
    ? "Email artifacts are up to date."
    : "Exported HTML/Jinja and plain-text templates.",
)
